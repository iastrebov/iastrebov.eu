#!/usr/bin/env python3
"""Create archive thumbnails without modifying the original article covers.

Run from any directory with Python 3 and Pillow installed:
    python3 scripts/generate_blog_thumbnails.py
    python3 scripts/generate_blog_thumbnails.py --check
"""

import argparse
from concurrent.futures import ThreadPoolExecutor
import io
import json
from pathlib import Path

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parents[1]
COVERS = ROOT / "assets/images/blog"
OUTPUT = COVERS / "thumbnails"
MANIFEST = ROOT / "_data/blog_thumbnails.yml"


def encode_thumbnail(source):
    with Image.open(source) as original:
        image = ImageOps.exif_transpose(original)
        image.thumbnail((640, 640), Image.Resampling.LANCZOS)
        if image.mode not in {"RGB", "RGBA"}:
            image = image.convert("RGBA" if "transparency" in image.info else "RGB")
        encoded = io.BytesIO()
        image.save(encoded, format="WEBP", quality=78, method=3)
        return source, encoded.getvalue(), image.size


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated files without writing")
    args = parser.parse_args()
    entries = []
    changed = []
    total_bytes = 0

    sources = [source for source in sorted(COVERS.iterdir())
               if source.suffix.lower() in {".png", ".jpg", ".jpeg", ".webp"}]
    with ThreadPoolExecutor(max_workers=4) as executor:
        thumbnails = list(executor.map(encode_thumbnail, sources))

    for source, data, (width, height) in thumbnails:
        target = OUTPUT / (source.stem + ".webp")
        total_bytes += len(data)
        if not target.exists() or target.read_bytes() != data:
            changed.append(str(target.relative_to(ROOT)))
            if not args.check:
                OUTPUT.mkdir(parents=True, exist_ok=True)
                target.write_bytes(data)
        entries.extend([
            json.dumps(source.relative_to(ROOT).as_posix()) + ":",
            "  url: " + json.dumps("/" + target.relative_to(ROOT).as_posix()),
            f"  width: {width}",
            f"  height: {height}",
        ])

    manifest = "# Generated by scripts/generate_blog_thumbnails.py; do not edit manually.\n"
    manifest += "\n".join(entries) + "\n"
    if not MANIFEST.exists() or MANIFEST.read_text() != manifest:
        changed.append(str(MANIFEST.relative_to(ROOT)))
        if not args.check:
            MANIFEST.parent.mkdir(parents=True, exist_ok=True)
            MANIFEST.write_text(manifest)
    print(f"{len(entries) // 4} thumbnails, {total_bytes / 1024 / 1024:.2f} MiB total")
    if args.check and changed:
        parser.exit(1, "Outdated generated files:\n" + "\n".join(changed) + "\n")
    print("Generated files are current." if args.check else f"Updated {len(changed)} files.")


if __name__ == "__main__":
    main()
